def _env() -> Environment:
    env = Environment(
        loader=_InlineLoader({"report.html": HTML_TEMPLATE, "report.md": MD_TEMPLATE}),
        autoescape=select_autoescape(["html"]),
        trim_blocks=True,
        lstrip_blocks=True,
    )
    return env


def render_html(payload: dict[str, Any]) -> str:
    return _env().get_template("report.html").render(**payload)


def render_markdown(payload: dict[str, Any]) -> str:
    # markdown output must not HTML-escape
    env = Environment(
        loader=_InlineLoader({"report.md": MD_TEMPLATE}),
        autoescape=False,
        trim_blocks=True,
        lstrip_blocks=True,
    )
    template = env.from_string(MD_TEMPLATE)
    return template.render(**payload)


def write_reports(
    payload: dict[str, Any],
    out_dir: str | Path,
    basename: str | None = None,
) -> dict[str, Path]:
    """Write HTML and Markdown reports; returns their paths."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    base = basename or (payload.get("trace") or {}).get("run_id") or payload.get("title", "report")
    base = "".join(ch if ch.isalnum() or ch in "-_" else "_" for ch in str(base))
    paths = {
        "html": out / f"{base}.html",
        "markdown": out / f"{base}.md",
    }
    paths["html"].write_text(render_html(payload), encoding="utf-8")
    paths["markdown"].write_text(render_markdown(payload), encoding="utf-8")
    return paths


